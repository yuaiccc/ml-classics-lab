export function getTrajectory(id: string): Trajectory | null {
  if (id === "gradient-descent") return runGradientDescent();
  if (id === "kmeans") return runKMeans();
  if (id === "logistic-regression") return runLogisticRegression();
  if (id === "perceptron") return runPerceptron();
  if (id === "linear-regression") return runLinearRegression();
  if (id === "pca") return runPCA();
  if (id === "dbscan") return runDBSCAN();
  if (id === "knn") return runKNN();
  if (id === "decision-tree") return runDecisionTree();
  if (id === "sarsa") return runSarsa();
  return null;
}
